export function placeholderContext(threadId?: string): PlaceholderContext {
  return threadId ? 'continuing' : 'new';
}

export function selectComposerPlaceholder(library: PlaceholderLibrary, previous: readonly string[] = [], random = Math.random) {
  const roll = random();
  const selected: PlaceholderTier = roll < 0.5 ? 'often' : roll < 0.85 ? 'sometimes' : 'rarely';
  const tiers: PlaceholderTier[] = [selected, ...(['often', 'sometimes', 'rarely'] as const).filter(tier => tier !== selected)];
  const recent = previous.slice(-5);
  for (const excluded of [recent, recent.slice(-1)]) {
    for (const tier of tiers) {
      const candidates = (library[tier] || []).filter(phrase => !excluded.includes(phrase));
      if (candidates.length) return candidates[Math.floor(random() * candidates.length)];
    }
  }
  return '';
}

export function createPlaceholderRotation(random = Math.random) {
  const recent: string[] = [];
  return (context: PlaceholderContext) => {
    const phrase = selectComposerPlaceholder(composerPlaceholderLibraries[context], recent, random);
    if (phrase) { recent.push(phrase); if (recent.length > 5) recent.shift(); }
    return phrase;
  };
}

export const nextComposerPlaceholder = createPlaceholderRotation();
